def heuristic_description(cluster, label):
    titles = [p["post_title"] for p in cluster[:3]]
    return f"Posts in this trend cluster around {label.lower()}, based on recurring titles such as: " + "；".join(titles)

def confidence_for_cluster(cluster):
    n = len(cluster)
    all_tokens = []
    for p in cluster:
        all_tokens.extend(p["tokens"])
    c = Counter(all_tokens)
    shared = sum(1 for _, v in c.items() if v >= 2)

    if n >= 4 and shared >= 3:
        return "high"
    if n >= 2 and shared >= 1:
        return "medium"
    return "low"

