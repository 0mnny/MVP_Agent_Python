# greedy clustering by token overlap
for i, post in enumerate(posts):
    if post["post_id"] in used:
        continue

    cluster = [post]
    used.add(post["post_id"])

    for j in range(i + 1, len(posts)):
        other = posts[j]
        if other["post_id"] in used:
            continue

        sim = jaccard(post["tokens"], other["tokens"])

        # looser threshold because titles are short/noisy
        if sim >= 0.18 or len(set(post["tokens"]) & set(other["tokens"])) >= 2:
            cluster.append(other)
            used.add(other["post_id"])

    clusters.append(cluster)

