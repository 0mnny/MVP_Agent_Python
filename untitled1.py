def extract_tokens(text):
    text = str(text).lower()

    # keep chinese chunks + ascii words
    zh_chunks = re.findall(r"[\u4e00-\u9fff]{1,6}", text)
    en_chunks = re.findall(r"[a-zA-Z][a-zA-Z0-9\-\_]{1,20}", text)

    tokens = []
    for tok in zh_chunks + en_chunks:
        tok = tok.strip().lower()
        if not tok:
            continue
        if tok in STOPWORDS or tok in EN_STOPWORDS:
            continue
        if len(tok) == 1:
            continue
        tokens.append(tok)

    # lightweight phrase boosts for common fashion patterns
    phrase_hits = []
    phrases = [
        "大码", "显瘦", "通勤", "极简", "复古", "甜妹", "芭蕾", "日系", "韩系", "牛仔",
        "短袖", "衬衫", "裙", "裤", "仙女", "夏日", "出游", "look", "vintage", "balletcore"
    ]
    for p in phrases:
        if p.lower() in text:
            phrase_hits.append(p.lower())

    return list(tokens + phrase_hits)

